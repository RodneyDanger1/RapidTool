/**
 * T-14: honest phase-coverage census — a pure function of the persisted graph
 * state (phase records + artifact rows), never a hard-coded "all 13 ran".
 */
export type PhaseCoverage = {
  /** Real phases (0..12) whose record status is "complete". */
  executed: number;
  /** Real phases in the graph today (PHASES.length — 13). */
  total: number;
  /** DELIVERABLE artifact rows contributed by the tail window
   *  P{tailStart}..P{last}. The bookkeeping rows — the packet's own row
   *  (kind "packet") and each phase's recorded DoD verdict (kind "gate") — are
   *  excluded, so the count is what the phase producers wrote and does not
   *  depend on which driver recorded gates. See phaseCoverage. */
  tailArtifacts: number;
  /** First id of the tail window `tailArtifacts` counts. */
  tailStart: PhaseId;
  /** W50/336-1: complete phases that recorded NO deliverable artifact row (a
   *  gate/packet bookkeeping row alone does not count). A phase that completed
   *  without producing anything is a silent no-op; this names it instead of
   *  hiding it behind the tail total. Empty on every driven run today. */
  emptyPhases: PhaseId[];
};

/**
 * T-14 (106 §6, finding F-11): compute the honest coverage census. The graph
 * is strictly linear, so a run stopped at P6 executed 7 of 13 phases and the
 * tail P7–P12 produced 0 artifacts — every surface must say exactly that and
 * never imply all 13 ran. Pure: derived from the given records + artifact
 * rows only, and defensive against sparse/hand-built payloads:
 *
 *  - records are matched by id (like `priorsSealed`, never by array
 *    position), so an unsorted/sparse status array can not mis-count;
 *  - foreign or non-integer phase ids never inflate the artifact census;
 *  - the two BOOKKEEPING rows are not phase deliverables: the packet's own row
 *    (kind "packet" — `sealPacketArtifact` re-stamps it at whatever phase the
 *    run stopped at) and each phase's recorded DoD verdict (kind "gate" — the
 *    driver records it, so counting it would make the same 13-phase run report
 *    a different total under a different driver). The packet's "## Artifacts
 *    (trimmed)" section hides it for the same reason; the census stays
 *    consistent with what is shown;
 *  - a complete phase with NO deliverable row is reported in `emptyPhases`
 *    (a silent no-op is named, never hidden behind the tail total).
 */
export function phaseCoverage(
  phases: readonly { id: number; status: string }[],
  artifacts: readonly { phase: number; kind?: string }[],
): PhaseCoverage {
  const records = Array.isArray(phases) ? phases : [];
  const rows = Array.isArray(artifacts) ? artifacts : [];
  // First-wins per id, mirroring priorsSealed's `.find` semantics.
  const statusById = new Map<number, string>();
  for (const r of records) {
    if (r && !statusById.has(r.id)) statusById.set(r.id, r.status);
  }
  let executed = 0;
  for (const def of PHASES) {
    if (statusById.get(def.id) === "complete") executed += 1;
  }
  const isBookkeeping = (kind: string | undefined): boolean => kind === "packet" || kind === "gate";
  const deliverableByPhase = new Map<number, number>();
  let tailArtifacts = 0;
  for (const a of rows) {
    if (!a || typeof a.phase !== "number" || !Number.isInteger(a.phase)) continue;
    if (isBookkeeping(a.kind)) continue;
    deliverableByPhase.set(a.phase, (deliverableByPhase.get(a.phase) ?? 0) + 1);
    if (a.phase < PHASE_TAIL_START || a.phase >= PHASES.length) continue;
    tailArtifacts += 1;
  }
  const emptyPhases: PhaseId[] = [];
  for (const def of PHASES) {
    if (statusById.get(def.id) !== "complete") continue;
    if ((deliverableByPhase.get(def.id) ?? 0) === 0) emptyPhases.push(def.id);
  }
  return { executed, total: PHASES.length, tailArtifacts, tailStart: PHASE_TAIL_START, emptyPhases };
}

/**
 * T-14: the one deterministic coverage line every surface shares, e.g.
 * "7 of 13 phases executed / 0 artifacts from P7–P12". Built from the real
 * census (never templated), so a full run honestly reports its own numbers.
 */
export function phaseCoverageLine(coverage: PhaseCoverage): string {
  // F3-20 (A20): look ids up in PHASE_BY_ID — never index PHASES by position.
  // The old `PHASES[coverage.tailStart]` silently renamed the window if the
  // array were ever reordered; ids are the graph's key (same law as
  // priorsSealed/phaseCoverage above).
  const fromDef = PHASE_BY_ID.get(coverage.tailStart);
  const lastDef = PHASES[PHASES.length - 1];
  const toDef = lastDef ? PHASE_BY_ID.get(lastDef.id) : undefined;
  const from = fromDef?.code ?? "P7";
  const to = toDef?.code ?? "P12";
  const noun = coverage.tailArtifacts === 1 ? "artifact" : "artifacts";
  return `${coverage.executed} of ${coverage.total} phases executed / ${coverage.tailArtifacts} ${noun} from ${from}–${to}`;
}
